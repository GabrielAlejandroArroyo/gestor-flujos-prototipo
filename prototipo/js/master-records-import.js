/** @typedef {"error"|"warn"|"info"} ImportIssueSeverity */
/** @typedef {{ code: string; severity: ImportIssueSeverity; column?: string; message: string; rawValue?: string; suggested?: string }} ImportIssue */
/** @typedef {{ entityId: string; entityName: string; attrKey: string; attrLabel: string; type: string; required: boolean; refEntityId: string | null; header: string }} ImportColumnSpec */

/**
 * @param {string} text
 */
function normalizeHeaderKey(text) {
  return String(text ?? "")
    .trim()
    .toLowerCase()
    .normalize("NFD")
    .replace(/\p{M}/gu, "")
    .replace(/\s+/g, " ");
}

/**
 * @param {object} state
 * @param {string} definitionId
 * @returns {ImportColumnSpec[]}
 */
export function buildMasterRecordImportColumnSpecs(state, definitionId) {
  const def = getMasterDefinitionById(state, definitionId);
  if (!def) return [];
  /** @type {ImportColumnSpec[]} */
  const specs = [];
  for (const entityId of def.entityIds ?? []) {
    const entity = getEntityById(state, entityId);
    if (!entity) continue;
    for (const raw of entity.attributes ?? []) {
      const attr = normalizeEntityAttribute(raw);
      if (!attr.key || isEntityAttributeAutoGenerated(attr)) continue;
      specs.push({
        entityId,
        entityName: entity.name,
        attrKey: attr.key,
        attrLabel: attr.label || attr.key,
        type: attr.type,
        required: !!attr.required,
        refEntityId: attr.type === ENTITY_REF_TYPE ? attr.refEntityId ?? null : null,
        header: `${entity.name}.${attr.key}`,
      });
    }
  }
  return specs;
}

/**
 * @param {ImportColumnSpec[]} specs
 */
export function buildMasterRecordImportCsvTemplate(specs) {
  const headers = specs.map((s) => s.header);
  const hints = specs.map((s) => {
    let hint = s.type;
    if (s.required) hint += "; obligatorio";
    if (s.type === ENTITY_REF_TYPE) hint += "; nombre o id de entidad referenciada";
    if (s.type === "si_no") hint += "; sí/no, true/false, 1/0";
    if (s.type === "fecha") hint += "; YYYY-MM-DD o DD/MM/YYYY";
    return hint;
  });
  const escape = (v) => {
    const s = String(v ?? "");
    if (/[",;\n\r]/.test(s)) return `"${s.replace(/"/g, '""')}"`;
    return s;
  };
  return `${headers.map(escape).join(";")}\n${hints.map(escape).join(";")}\n`;
}

/**
 * @param {string} text
 */
export function parseDelimitedImportText(text) {
  const raw = String(text ?? "").replace(/^\uFEFF/, "");
  const lines = raw.split(/\r?\n/).filter((line) => line.trim() !== "");
  if (!lines.length) {
    return { headers: [], rows: [], delimiter: ";" };
  }
  const sample = lines[0];
  const semi = (sample.match(/;/g) ?? []).length;
  const comma = (sample.match(/,/g) ?? []).length;
  const delimiter = semi >= comma ? ";" : ",";

  /** @param {string} line */
  function splitLine(line) {
    /** @type {string[]} */
    const out = [];
    let cur = "";
    let inQuotes = false;
    for (let i = 0; i < line.length; i += 1) {
      const ch = line[i];
      if (ch === '"') {
        if (inQuotes && line[i + 1] === '"') {
          cur += '"';
          i += 1;
        } else {
          inQuotes = !inQuotes;
        }
        continue;
      }
      if (!inQuotes && ch === delimiter) {
        out.push(cur.trim());
        cur = "";
        continue;
      }
      cur += ch;
    }
    out.push(cur.trim());
    return out;
  }

  const headers = splitLine(lines[0]);
  const rows = lines.slice(1).map((line, idx) => ({
    lineNumber: idx + 2,
    cells: splitLine(line),
  }));
  return { headers, rows, delimiter };
}

/**
 * @param {File} file
 * @returns {Promise<{ headers: string[]; rows: { lineNumber: number; cells: string[] }[]; delimiter: string; format: string }>}
 */
export async function parseMasterRecordImportFile(file) {
  const name = String(file.name ?? "").toLowerCase();
  if (name.endsWith(".csv") || name.endsWith(".txt")) {
    const text = await file.text();
    const parsed = parseDelimitedImportText(text);
    return { ...parsed, format: "csv" };
  }
  if (name.endsWith(".xlsx") || name.endsWith(".xls")) {
    const xlsx = /** @type {typeof import("xlsx") | undefined} */ (globalThis.XLSX);
    if (!xlsx?.read) {
      throw new Error(
        "Excel no disponible sin conexión. Guardá el archivo como CSV o abrí el mock con internet para cargar la librería XLSX.",
      );
    }
    const buf = await file.arrayBuffer();
    const wb = xlsx.read(buf, { type: "array" });
    const sheetName = wb.SheetNames[0];
    if (!sheetName) {
      return { headers: [], rows: [], delimiter: ";", format: "xlsx" };
    }
    const sheet = wb.Sheets[sheetName];
    const matrix = xlsx.utils.sheet_to_json(sheet, { header: 1, defval: "", raw: false });
    if (!matrix.length) {
      return { headers: [], rows: [], delimiter: ";", format: "xlsx" };
    }
    const headers = (matrix[0] ?? []).map((c) => String(c ?? "").trim());
    const rows = matrix.slice(1).map((row, idx) => ({
      lineNumber: idx + 2,
      cells: headers.map((_, colIdx) => String(row?.[colIdx] ?? "").trim()),
    }));
    return { headers, rows, delimiter: ";", format: "xlsx" };
  }
  throw new Error("Formato no soportado. Usá CSV (.csv) o Excel (.xlsx).");
}

/**
 * @param {ImportColumnSpec} spec
 * @param {string} header
 */
function headerMatchesSpec(spec, header) {
  const h = normalizeHeaderKey(header);
  if (!h) return false;
  const candidates = [
    spec.header,
    `${spec.entityName}.${spec.attrKey}`,
    `${spec.entityName}.${spec.attrLabel}`,
    spec.attrKey,
    spec.attrLabel,
    `${spec.entityName}_${spec.attrKey}`,
  ].map(normalizeHeaderKey);
  return candidates.includes(h);
}

/**
 * @param {ImportColumnSpec[]} specs
 * @param {string[]} headers
 */
export function mapImportHeadersToSpecs(specs, headers) {
  /** @type {Map<number, ImportColumnSpec>} */
  const indexToSpec = new Map();
  /** @type {ImportIssue[]} */
  const columnIssues = [];
  const usedSpecs = new Set();

  headers.forEach((header, index) => {
    const h = String(header ?? "").trim();
    if (!h || h.startsWith("#")) return;
    const spec = specs.find((s) => !usedSpecs.has(s.header) && headerMatchesSpec(s, h));
    if (spec) {
      indexToSpec.set(index, spec);
      usedSpecs.add(spec.header);
      if (normalizeHeaderKey(h) !== normalizeHeaderKey(spec.header)) {
        columnIssues.push({
          code: "COLUMN_ALIAS",
          severity: "info",
          column: h,
          message: `Columna «${h}» mapeada a «${spec.header}».`,
        });
      }
      return;
    }
    columnIssues.push({
      code: "COLUMN_UNKNOWN",
      severity: "error",
      column: h,
      message: `Columna «${h}» no coincide con ningún campo del maestro.`,
    });
  });

  for (const spec of specs) {
    if (!usedSpecs.has(spec.header)) {
      columnIssues.push({
        code: "COLUMN_MISSING",
        severity: spec.required ? "error" : "warn",
        column: spec.header,
        message: spec.required
          ? `Falta la columna obligatoria «${spec.header}».`
          : `Columna opcional «${spec.header}» no está en el archivo.`,
      });
    }
  }

  return { indexToSpec, columnIssues };
}

/**
 * @param {object} state
 * @param {string | null} refEntityId
 * @param {string} raw
 */
function resolveRefEntityValue(state, refEntityId, raw) {
  const trimmed = String(raw ?? "").trim();
  if (!trimmed) return { ok: true, value: "" };
  if (!refEntityId) {
    return { ok: false, message: "Referencia sin entidad destino configurada." };
  }
  const target = getEntityById(state, refEntityId);
  if (!target) {
    return { ok: false, message: "La entidad referenciada no existe en el catálogo." };
  }
  if (trimmed === target.id) return { ok: true, value: target.id };
  const norm = normalizeHeaderKey(trimmed);
  if (target && normalizeHeaderKey(target.name) === norm) {
    return { ok: true, value: target.id };
  }
  return {
    ok: false,
    message: `No hay match para «${trimmed}» en la entidad «${target.name}».`,
    suggested: target.name,
  };
}

/**
 * @param {ImportColumnSpec} spec
 * @param {string} raw
 * @param {object} state
 */
function coerceImportCellValue(spec, raw, state) {
  /** @type {ImportIssue[]} */
  const issues = [];
  let value = String(raw ?? "");
  const trimmed = value.trim();
  if (trimmed !== value) {
    issues.push({
      code: "NORMALIZE_TRIM",
      severity: "warn",
      column: spec.header,
      message: "Espacios al inicio o final.",
      rawValue: value,
      suggested: trimmed,
    });
    value = trimmed;
  }
  if (value === "") {
    if (spec.required && spec.type !== "si_no") {
      issues.push({
        code: "REQUIRED",
        severity: "error",
        column: spec.header,
        message: "Valor obligatorio vacío.",
      });
    }
    return { value: spec.type === "si_no" ? false : "", issues };
  }

  if (spec.type === "numero") {
    const normalized = value.replace(/\s/g, "").replace(",", ".");
    const num = Number(normalized);
    if (!Number.isFinite(num)) {
      issues.push({
        code: "TYPE_NUMBER",
        severity: "error",
        column: spec.header,
        message: `«${value}» no es un número válido.`,
        rawValue: value,
      });
      return { value: "", issues };
    }
    if (normalized !== value.replace(/\s/g, "")) {
      issues.push({
        code: "NORMALIZE_DECIMAL",
        severity: "warn",
        column: spec.header,
        message: "Separador decimal normalizado.",
        rawValue: value,
        suggested: String(num),
      });
    }
    return { value: num, issues };
  }

  if (spec.type === "si_no") {
    const v = normalizeHeaderKey(value);
    if (["si", "sí", "true", "1", "yes", "y"].includes(v)) return { value: true, issues };
    if (["no", "false", "0", "n"].includes(v)) return { value: false, issues };
    issues.push({
      code: "TYPE_BOOLEAN",
      severity: "error",
      column: spec.header,
      message: `«${value}» no es un valor sí/no reconocido.`,
      rawValue: value,
      suggested: "sí / no",
    });
    return { value: false, issues };
  }

  if (spec.type === "fecha") {
    if (/^\d{4}-\d{2}-\d{2}$/.test(value)) return { value, issues };
    const m = value.match(/^(\d{1,2})[\/\-](\d{1,2})[\/\-](\d{4})$/);
    if (m) {
      const dd = m[1].padStart(2, "0");
      const mm = m[2].padStart(2, "0");
      const iso = `${m[3]}-${mm}-${dd}`;
      issues.push({
        code: "NORMALIZE_DATE",
        severity: "warn",
        column: spec.header,
        message: "Fecha convertida a formato ISO.",
        rawValue: value,
        suggested: iso,
      });
      return { value: iso, issues };
    }
    issues.push({
      code: "TYPE_DATE",
      severity: "error",
      column: spec.header,
      message: `«${value}» no es una fecha válida (use YYYY-MM-DD o DD/MM/YYYY).`,
      rawValue: value,
    });
    return { value: "", issues };
  }

  if (spec.type === ENTITY_REF_TYPE) {
    const ref = resolveRefEntityValue(state, spec.refEntityId, value);
    if (!ref.ok) {
      issues.push({
        code: "REF_NO_MATCH",
        severity: "error",
        column: spec.header,
        message: ref.message ?? "Sin match de referencia.",
        rawValue: value,
        suggested: ref.suggested,
      });
      return { value: "", issues };
    }
    return { value: ref.value, issues };
  }

  return { value, issues };
}

/**
 * @param {object} state
 * @param {string} definitionId
 * @param {string[]} headers
 * @param {{ lineNumber: number; cells: string[] }[]} rows
 * @param {{ applyNormalizations?: boolean }} [opts]
 */
export function validateMasterRecordImport(state, definitionId, headers, rows, opts = {}) {
  const specs = buildMasterRecordImportColumnSpecs(state, definitionId);
  const { indexToSpec, columnIssues } = mapImportHeadersToSpecs(specs, headers);
  const hasBlockingColumnErrors = columnIssues.some(
    (i) => i.severity === "error" && i.code.startsWith("COLUMN_"),
  );

  /** @type {Array<{ lineNumber: number; status: "valid"|"invalid"|"normalize"; values: Record<string, Record<string, unknown>>; issues: ImportIssue[] }>} */
  const rowResults = [];

  for (const row of rows) {
    /** @type {Record<string, Record<string, unknown>>} */
    const values = {};
    /** @type {ImportIssue[]} */
    const issues = [];
    for (const spec of specs) {
      if (!values[spec.entityId]) values[spec.entityId] = {};
    }

    indexToSpec.forEach((spec, colIndex) => {
      const raw = row.cells[colIndex] ?? "";
      const coerced = coerceImportCellValue(spec, raw, state);
      let finalValue = coerced.value;
      for (const issue of coerced.issues) {
        if (issue.severity === "warn" && opts.applyNormalizations && issue.suggested != null) {
          if (issue.code === "NORMALIZE_TRIM") finalValue = issue.suggested;
          if (issue.code === "NORMALIZE_DECIMAL") finalValue = Number(issue.suggested);
          if (issue.code === "NORMALIZE_DATE") finalValue = issue.suggested;
        }
        issues.push(issue);
      }
      if (!values[spec.entityId]) values[spec.entityId] = {};
      values[spec.entityId][spec.attrKey] = finalValue;
    });

    if (!hasBlockingColumnErrors) {
      const business = validateMasterRecordValues(state, definitionId, values);
      if (!business.ok) {
        issues.push({
          code: "BUSINESS_RULE",
          severity: "error",
          message: business.message,
        });
      }
    }

    const hasError = issues.some((i) => i.severity === "error") || hasBlockingColumnErrors;
    const hasWarn = issues.some((i) => i.severity === "warn");
    rowResults.push({
      lineNumber: row.lineNumber,
      status: hasError ? "invalid" : hasWarn ? "normalize" : "valid",
      values,
      issues,
    });
  }

  const summary = {
    totalRows: rowResults.length,
    validRows: rowResults.filter((r) => r.status === "valid").length,
    normalizeRows: rowResults.filter((r) => r.status === "normalize").length,
    invalidRows: rowResults.filter((r) => r.status === "invalid").length,
    columnIssues,
    hasBlockingColumnErrors,
  };

  return { specs, rowResults, summary };
}

/**
 * @param {ImportIssue[]} issues
 */
export function importIssueLabel(issue) {
  const map = {
    COLUMN_UNKNOWN: "Columna sin match",
    COLUMN_MISSING: "Columna faltante",
    COLUMN_ALIAS: "Columna alias",
    REQUIRED: "Obligatorio",
    TYPE_NUMBER: "Tipo número",
    TYPE_DATE: "Tipo fecha",
    TYPE_BOOLEAN: "Tipo sí/no",
    REF_NO_MATCH: "Referencia sin match",
    NORMALIZE_TRIM: "Normalizar espacios",
    NORMALIZE_DECIMAL: "Normalizar decimal",
    NORMALIZE_DATE: "Normalizar fecha",
    BUSINESS_RULE: "Regla de negocio",
  };
  return map[issue.code] ?? issue.code;
}

/**
 * @param {object} state
 * @param {string} definitionId
 * @param {Array<{ lineNumber: number; status: string; values: Record<string, Record<string, unknown>> }>} rowResults
 * @param {{ applyNormalizations?: boolean; includeNormalizeStatus?: boolean }} opts
 * @returns {{ created: number; skipped: number }}
 */
export function buildMasterRecordsFromImportRowResults(
  state,
  definitionId,
  rowResults,
  opts = {},
) {
  const includeNormalize = opts.includeNormalizeStatus !== false;
  const eligible = rowResults.filter((r) => {
    if (r.status === "valid") return true;
    if (includeNormalize && r.status === "normalize" && opts.applyNormalizations) return true;
    return false;
  });
  let created = 0;
  let skipped = rowResults.length - eligible.length;
  const now = new Date().toISOString();
  if (!Array.isArray(state.masterRecords)) state.masterRecords = [];
  for (const row of eligible) {
    const values = structuredClone
      ? structuredClone(row.values)
      : JSON.parse(JSON.stringify(row.values));
    applyAutoGeneratedAttributeValues(state, definitionId, values, { isCreate: true });
    const check = validateMasterRecordValues(state, definitionId, values);
    if (!check.ok) {
      skipped += 1;
      continue;
    }
    const newId = createId("masterRecord");
    state.masterRecords.push({
      id: newId,
      lineageId: newId,
      definitionId,
      values,
      status: "vigente",
      version: 1,
      history: [],
      createdAt: now,
      updatedAt: now,
    });
    created += 1;
  }
  return { created, skipped };
}
