import {
  generateEntityAttributeAutoValue,
  getEntityById,
  isEntityAttributeAutoGenerated,
  normalizeEntityAttribute,
} from "./entities.js";
import { getMasterDefinitionById } from "./master-definitions.js";

export { getMasterDefinitionById } from "./master-definitions.js";

/** @typedef {"vigente"|"historico"} MasterRecordStatus */

/** @typedef {{ version: number; values: Record<string, Record<string, unknown>>; archivedAt: string; updatedAt?: string }} MasterRecordHistoryEntry */

/**
 * @typedef {{
 *   id: string;
 *   definitionId: string;
 *   values: Record<string, Record<string, unknown>>;
 *   createdAt: string;
 *   updatedAt: string;
 *   status: MasterRecordStatus;
 *   version: number;
 *   history: MasterRecordHistoryEntry[];
 *   lineageId: string;
 * }} MasterRecord
 */

/**
 * @param {object} state
 */
export function ensureMasterRecordsState(state) {
  if (!state || typeof state !== "object") return state;
  if (!Array.isArray(state.masterRecords)) state.masterRecords = [];
  const validDefIds = new Set((state.masterDefinitions ?? []).map((d) => d.id));
  state.masterRecords = state.masterRecords
    .filter((r) => validDefIds.has(String(r.definitionId)))
    .map((r) => {
      const norm = normalizeMasterRecord(r);
      norm.values = syncMasterRecordValuesWithDefinition(state, norm.definitionId, norm.values);
      return norm;
    });
  return state;
}

/**
 * Alinea valores del registro con la definición actual (entidades/atributos del menú Definición de maestros).
 *
 * @param {object} state
 * @param {string} definitionId
 * @param {Record<string, Record<string, unknown>> | null | undefined} values
 */
export function syncMasterRecordValuesWithDefinition(state, definitionId, values) {
  const base = buildEmptyValuesForDefinition(state, definitionId);
  const def = getMasterDefinitionById(state, definitionId);
  if (!def) return base;
  /** @type {Record<string, Record<string, unknown>>} */
  const merged = {};
  for (const entityId of def.entityIds ?? []) {
    const entity = getEntityById(state, entityId);
    const allowedKeys = new Set(
      (entity?.attributes ?? []).map((a) => normalizeEntityAttribute(a).key).filter(Boolean),
    );
    merged[entityId] = { ...(base[entityId] ?? {}) };
    const prev = values?.[entityId] ?? {};
    for (const key of allowedKeys) {
      if (Object.prototype.hasOwnProperty.call(prev, key)) {
        merged[entityId][key] = prev[key];
      }
    }
  }
  return merged;
}

/**
 * @param {object} raw
 * @returns {MasterRecord}
 */
/**
 * @param {Record<string, Record<string, unknown>> | null | undefined} values
 */
export function cloneMasterRecordValues(values) {
  /** @type {Record<string, Record<string, unknown>>} */
  const out = {};
  if (!values || typeof values !== "object") return out;
  for (const [entityId, bag] of Object.entries(values)) {
    if (!bag || typeof bag !== "object") continue;
    out[String(entityId)] = { ...bag };
  }
  return out;
}

/**
 * @param {unknown} raw
 * @returns {MasterRecordHistoryEntry[]}
 */
function normalizeMasterRecordHistory(raw) {
  if (!Array.isArray(raw)) return [];
  /** @type {MasterRecordHistoryEntry[]} */
  const entries = [];
  for (const item of raw) {
    if (!item || typeof item !== "object") continue;
    const version = Number(item.version);
    if (!Number.isFinite(version) || version < 1) continue;
    entries.push({
      version,
      values: cloneMasterRecordValues(item.values),
      archivedAt: String(item.archivedAt ?? new Date().toISOString()),
      updatedAt: item.updatedAt ? String(item.updatedAt) : undefined,
    });
  }
  return entries.sort((a, b) => b.version - a.version);
}

export function normalizeMasterRecord(raw) {
  const values = cloneMasterRecordValues(raw?.values);
  const now = new Date().toISOString();
  const id = raw?.id ? String(raw.id) : createId("masterRecord");
  const statusRaw = raw?.status;
  const status =
    statusRaw === "historico" ? "historico" : "vigente";
  const version =
    typeof raw?.version === "number" && raw.version >= 1 ? raw.version : 1;
  return {
    id,
    definitionId: String(raw?.definitionId ?? ""),
    values,
    createdAt: String(raw?.createdAt ?? now),
    updatedAt: String(raw?.updatedAt ?? raw?.createdAt ?? now),
    status,
    version,
    history: normalizeMasterRecordHistory(raw?.history),
    lineageId: String(raw?.lineageId ?? id),
  };
}

/**
 * @param {MasterRecord} record
 */
export function masterRecordUsageStatusLabel(record) {
  if (record?.status === "historico") return "Histórico";
  const v = record?.version ?? 1;
  return v > 1 ? `Vigente · v${v}` : "Vigente";
}

/**
 * @param {object} state
 * @param {string} definitionId
 */
export function listVigenteMasterRecordsForDefinition(state, definitionId) {
  if (!definitionId) return [];
  return (state.masterRecords ?? []).filter(
    (r) => r.definitionId === definitionId && (r.status ?? "vigente") === "vigente",
  );
}

/**
 * Archiva la revisión actual antes de aplicar cambios (queda en historial; el registro sigue vigente).
 *
 * @param {MasterRecord} record
 */
/**
 * @param {Record<string, Record<string, unknown>> | null | undefined} a
 * @param {Record<string, Record<string, unknown>> | null | undefined} b
 */
export function masterRecordValuesEqual(a, b) {
  return JSON.stringify(a ?? {}) === JSON.stringify(b ?? {});
}

export function pushMasterRecordHistoryBeforeUpdate(record) {
  if (!Array.isArray(record.history)) record.history = [];
  const prevVersion = record.version ?? 1;
  record.history.unshift({
    version: prevVersion,
    values: cloneMasterRecordValues(record.values),
    archivedAt: new Date().toISOString(),
    updatedAt: record.updatedAt,
  });
  if (record.history.length > 100) {
    record.history.length = 100;
  }
  record.version = prevVersion + 1;
}

/**
 * @param {object} state
 * @param {string} definitionId
 */
export function countMasterRecordsForDefinition(state, definitionId) {
  return listVigenteMasterRecordsForDefinition(state, definitionId).length;
}

/**
 * @param {object} state
 * @param {string} recordId
 */
export function getMasterRecordById(state, recordId) {
  if (!recordId) return null;
  return state.masterRecords?.find((r) => r.id === recordId) ?? null;
}

/**
 * @param {object} state
 * @param {string} definitionId
 */
export function buildEmptyValuesForDefinition(state, definitionId) {
  /** @type {Record<string, Record<string, unknown>>} */
  const values = {};
  const def = getMasterDefinitionById(state, definitionId);
  if (!def) return values;
  for (const entityId of def.entityIds ?? []) {
    const entity = getEntityById(state, entityId);
    if (!entity) continue;
    values[entityId] = {};
    for (const raw of entity.attributes ?? []) {
      const attr = normalizeEntityAttribute(raw);
      if (!attr.key) continue;
      if (isEntityAttributeAutoGenerated(attr)) {
        values[entityId][attr.key] = "";
      } else if (attr.type === "si_no") {
        values[entityId][attr.key] = false;
      } else {
        values[entityId][attr.key] = "";
      }
    }
  }
  return values;
}

/**
 * @param {object} state
 * @param {string} definitionId
 * @param {Record<string, Record<string, unknown>>} values
 * @param {{ isCreate?: boolean }} [opts]
 */
export function applyAutoGeneratedAttributeValues(state, definitionId, values, opts = {}) {
  const def = getMasterDefinitionById(state, definitionId);
  if (!def) return values;
  for (const entityId of def.entityIds ?? []) {
    const entity = getEntityById(state, entityId);
    if (!entity) continue;
    if (!values[entityId]) values[entityId] = {};
    for (const raw of entity.attributes ?? []) {
      const attr = normalizeEntityAttribute(raw);
      if (!attr.key || !isEntityAttributeAutoGenerated(attr)) continue;
      const current = values[entityId][attr.key];
      if (opts.isCreate || current === "" || current == null) {
        values[entityId][attr.key] = generateEntityAttributeAutoValue(attr) ?? "";
      }
    }
  }
  return values;
}

/**
 * @param {object} state
 * @param {string} definitionId
 * @param {Record<string, Record<string, unknown>>} values
 * @returns {{ ok: true } | { ok: false; message: string }}
 */
export function validateMasterRecordValues(state, definitionId, values) {
  const def = getMasterDefinitionById(state, definitionId);
  if (!def) {
    return { ok: false, message: "La definición de maestros seleccionada ya no existe." };
  }
  if (!(def.entityIds ?? []).length) {
    return { ok: false, message: "La definición no tiene entidades configuradas." };
  }
  for (const entityId of def.entityIds) {
    const entity = getEntityById(state, entityId);
    if (!entity) {
      return { ok: false, message: "Falta una entidad de la definición en el catálogo." };
    }
    const entityValues = values[entityId] ?? {};
    for (const raw of entity.attributes ?? []) {
      const attr = normalizeEntityAttribute(raw);
      if (!attr.key || isEntityAttributeAutoGenerated(attr)) continue;
      if (!attr.required) continue;
      const val = entityValues[attr.key];
      if (attr.type === "si_no") {
        continue;
      }
      if (val === "" || val == null) {
        return {
          ok: false,
          message: `«${attr.label || attr.key}» (${entity.name}) es obligatorio.`,
        };
      }
    }
  }
  return { ok: true };
}

/**
 * @param {object} state
 * @param {MasterRecord} record
 */
/**
 * @param {object} state
 * @param {string} definitionId
 * @param {Record<string, Record<string, unknown>>} values
 */
export function summarizeMasterRecordValues(state, definitionId, values) {
  return summarizeMasterRecordForList(state, {
    definitionId,
    values,
  });
}

/**
 * @param {object} state
 * @param {MasterRecord} record
 */
export function summarizeMasterRecordForList(state, record) {
  const def = getMasterDefinitionById(state, record.definitionId);
  const parts = [];
  for (const entityId of def?.entityIds ?? []) {
    const entity = getEntityById(state, entityId);
    if (!entity) continue;
    const bag = record.values?.[entityId] ?? {};
    for (const raw of entity.attributes ?? []) {
      const attr = normalizeEntityAttribute(raw);
      if (!attr.key || isEntityAttributeAutoGenerated(attr)) continue;
      const v = bag[attr.key];
      if (v === "" || v == null) continue;
      parts.push(`${attr.label || attr.key}: ${String(v)}`);
      if (parts.length >= 3) break;
    }
    if (parts.length >= 3) break;
  }
  return parts.length ? parts.join(" · ") : "—";
}
